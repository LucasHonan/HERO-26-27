const matrix = (
  id: string,
  title: string,
  description: string,
  category: string,
  optionNames: string[],
): DecisionMatrix => {
  const criteria = [
    { id: `${id}-c1`, name: "Reliability", weight: 30, description: "Expected robustness during HERC field operations." },
    { id: `${id}-c2`, name: "Integration effort", weight: 20, description: "Implementation time and team learning curve." },
    { id: `${id}-c3`, name: "Telemetry support", weight: 15, description: "Ease of logging, diagnostics, and DRR/CDR evidence capture." },
    { id: `${id}-c4`, name: "Cost and availability", weight: 15, description: "Budget fit and access to parts or licenses." },
    { id: `${id}-c5`, name: "HERC fit", weight: 20, description: "Suitability for remote-controlled rover constraints." },
  ];

  return {
    id,
    title,
    description,
    category,
    criteria,
    options: optionNames.map((name, index) => ({
      id: `${id}-o${index + 1}`,
      name,
      notes: index === 0 ? "Baseline option for comparison." : "Candidate option under review.",
      pros: index === 0 ? ["Known ecosystem", "Good documentation"] : ["Useful capability", "Worth prototyping"],
      cons: index === 0 ? ["May need adapter code"] : ["Needs test evidence"],
      scores: Object.fromEntries(criteria.map((criterion, criterionIndex) => [criterion.id, Math.max(2, 5 - Math.abs(index - criterionIndex) % 4)])),
    })),
    createdAt: now,
    updatedAt: now,
  };
};

