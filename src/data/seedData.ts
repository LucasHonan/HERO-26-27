const tradeMatrix = (
  id: string,
  title: string,
  description: string,
  category: string,
  criteria: Array<[string, number, string]>,
  options: Array<[string, number[], string]>,
): DecisionMatrix => {
  const matrixCriteria = criteria.map(([name, weight, description], index) => ({
    id: `${id}-c${index + 1}`,
    name,
    weight,
    description,
  }));

  return {
    id,
    title,
    description,
    category,
    criteria: matrixCriteria,
    options: options.map(([name, scores, notes], index) => ({
      id: `${id}-o${index + 1}`,
      name,
      notes,
      pros: [],
      cons: [],
      scores: Object.fromEntries(matrixCriteria.map((criterion, criterionIndex) => [criterion.id, scores[criterionIndex] ?? 3])),
    })),
    createdAt: now,
    updatedAt: now,
  };
};

